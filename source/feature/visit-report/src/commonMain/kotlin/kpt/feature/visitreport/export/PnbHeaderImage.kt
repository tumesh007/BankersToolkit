fun decodeHex(hex: String): ByteArray {
    val result = ByteArray(hex.length / 2)
    for (i in result.indices) {
        val index = i * 2
        val j = hex.substring(index, index + 2).toInt(16)
        result[i] = j.toByte()
    }
    return result
}

